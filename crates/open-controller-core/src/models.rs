//! Controllers known by their USB ids: what they are called and which family they belong to,
//! which decides what their extra buttons are named, how they are drawn and what to tell the
//! user about them. Taken from SDL 3.4's own lists (`controller_list.h`, `usb_ids.h`, the
//! HIDAPI drivers and its built-in Windows mappings) plus the 8BitDo range. Which extra buttons
//! a controller really has is asked of SDL when it connects; this table only names them.

use crate::extras::Family;

/// (vendor, product, family, name).
pub type Row = (u16, u16, Family, &'static str);

pub fn lookup(vendor: u16, product: u16) -> Option<&'static Row> {
    MODELS.iter().find(|r| r.0 == vendor && r.1 == product)
}

/// Names SDL gives when it knows nothing better, which the table's name replaces.
pub fn is_generic_name(name: &str) -> bool {
    let n = name.to_ascii_lowercase();
    n.starts_with("xinput ")
        || n.contains("generic")
        || n.contains("usb joystick")
        || n.contains("usb gamepad")
        || n.contains("twin usb")
        || n == "controller"
        || n == "wireless controller"
        || n == "gamepad"
}

