#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ids_are_unique() {
        let mut ids: Vec<(u16, u16)> = MODELS.iter().map(|r| (r.0, r.1)).collect();
        ids.sort();
        let before = ids.len();
        ids.dedup();
        assert_eq!(ids.len(), before);
        assert!(before > 300);
    }

    #[test]
    fn known_models() {
        assert_eq!(lookup(0x2DC8, 0x6012).map(|r| r.2), Some(Family::EightBitDoFour));
        assert_eq!(lookup(0x054C, 0x0DF2).map(|r| r.2), Some(Family::DualSenseEdge));
        assert_eq!(lookup(0x054C, 0x0268).map(|r| r.2), Some(Family::DualShock3));
        assert!(MODELS.iter().all(|r| !r.3.is_empty() && r.3.len() < 80));
    }

    #[test]
    fn generic_names() {
        assert!(is_generic_name("XInput Controller #1"));
        assert!(is_generic_name("Twin USB Joystick"));
        assert!(!is_generic_name("DualSense Wireless Controller"));
    }
}
